param(
    [switch]$DryRun = $true
)

$ErrorActionPreference = "Stop"

$frontendDir = "D:\Stock\trading_assistant\20_tools_workspace\a5_p0_home_batch1_frontend"
$nmDir = Join-Path $frontendDir "node_modules"

Write-Host "========================================"
Write-Host "  delete_a5p0_node_modules.ps1"
Write-Host "========================================"
Write-Host ("Mode     : {0}" -f $(if ($DryRun) { "DRY RUN (preview only, no deletion)" } else { "REAL RUN (files WILL be deleted)" }))
Write-Host ("Target   : {0}" -f $nmDir)
Write-Host ""

if (-not (Test-Path $frontendDir)) {
    Write-Error "Frontend directory not found: $frontendDir"
    exit 1
}

if (-not (Test-Path $nmDir)) {
    Write-Host "node_modules directory does not exist. Nothing to do."
    Write-Host ""
    Write-Host "========== SUMMARY =========="
    Write-Host "Status   : SKIPPED (node_modules not found)"
    Write-Host "Files    : 0"
    Write-Host "Size     : 0 KB (0 MB)"
    Write-Host "Mode     : $(if ($DryRun) { "DRY RUN" } else { "REAL RUN" })"
    exit 0
}

$fileCount = 0
$sizeBytes = 0

$files = Get-ChildItem -Path $nmDir -Recurse -File -ErrorAction SilentlyContinue
foreach ($f in $files) {
    $fileCount++
    $sizeBytes += $f.Length
}

$sizeKB = [math]::Round($sizeBytes / 1KB, 2)
$sizeMB = [math]::Round($sizeBytes / 1MB, 2)

Write-Host "========== TARGET INFO =========="
Write-Host ("Files to delete : {0}" -f $fileCount)
Write-Host ("Size to delete  : {0} KB ({1} MB)" -f $sizeKB, $sizeMB)
Write-Host ""

if ($DryRun) {
    Write-Host "[DRY RUN] No files were deleted. Re-run with -DryRun:`$false to actually delete."
    $status = "DRY RUN COMPLETE (no deletion)"
} else {
    Write-Host "[REAL RUN] Deleting node_modules directory..."
    Remove-Item -Path $nmDir -Recurse -Force
    $stillExists = Test-Path $nmDir
    if ($stillExists) {
        Write-Error "Deletion failed: directory still exists after Remove-Item"
        exit 1
    }
    Write-Host "[REAL RUN] Deletion completed successfully."
    $status = "DELETED"
}

Write-Host ""
Write-Host "========================================"
Write-Host "            SUMMARY"
Write-Host "========================================"
Write-Host ("Status   : {0}" -f $status)
Write-Host ("Target   : {0}" -f $nmDir)
Write-Host ("Files    : {0}" -f $fileCount)
Write-Host ("Size     : {0} KB ({1} MB)" -f $sizeKB, $sizeMB)
Write-Host ("Mode     : {0}" -f $(if ($DryRun) { "DRY RUN" } else { "REAL RUN" }))
Write-Host "========================================"
